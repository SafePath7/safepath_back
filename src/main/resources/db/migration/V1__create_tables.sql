CREATE TABLE users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    firebase_uid VARCHAR(128) NOT NULL UNIQUE,
    name VARCHAR(100) NOT NULL,
    phone_hash VARCHAR(64) NOT NULL UNIQUE,
    phone_encrypted TEXT NOT NULL,
    email VARCHAR(255) NOT NULL UNIQUE,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    fcm_token TEXT
);

CREATE TABLE guardian_registrations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL,
    guardian_id BIGINT NOT NULL,
    requested_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    accepted_at TIMESTAMP,
    status VARCHAR(20) NOT NULL DEFAULT 'PENDING',
    can_view_location SMALLINT NOT NULL DEFAULT 0,
    can_view_status SMALLINT NOT NULL DEFAULT 0,
    can_view_personal_info SMALLINT NOT NULL DEFAULT 0,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_guardian_registrations_user FOREIGN KEY (user_id) REFERENCES users (id),
    CONSTRAINT fk_guardian_registrations_guardian FOREIGN KEY (guardian_id) REFERENCES users (id),
    CONSTRAINT uq_guardian_registrations_pair UNIQUE (user_id, guardian_id),
    CONSTRAINT ck_guardian_registrations_not_self CHECK (user_id <> guardian_id),
    CONSTRAINT ck_guardian_view_location CHECK (can_view_location IN (0, 1)),
    CONSTRAINT ck_guardian_view_status CHECK (can_view_status IN (0, 1)),
    CONSTRAINT ck_guardian_view_personal_info CHECK (can_view_personal_info IN (0, 1))
);

CREATE TABLE voice_profiles (
    user_id BIGINT PRIMARY KEY REFERENCES users (id),
    speaker_embedding REAL[] NOT NULL,
    audio_file_url TEXT NOT NULL,
    baseline_volume DOUBLE PRECISION NOT NULL,
    baseline_pitch DOUBLE PRECISION NOT NULL,
    model_version VARCHAR(50) NOT NULL,
    consented_at TIMESTAMP NOT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE safety_facilities (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    latitude DOUBLE PRECISION NOT NULL,
    longitude DOUBLE PRECISION NOT NULL,
    address VARCHAR(255) NOT NULL,
    facility_type VARCHAR(50) NOT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE safe_return_sessions (
    id UUID PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users (id),
    status VARCHAR(20) NOT NULL,
    started_at TIMESTAMP NOT NULL,
    ended_at TIMESTAMP,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE risk_events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    session_id UUID NOT NULL REFERENCES safe_return_sessions (id),
    event_type VARCHAR(20) NOT NULL,
    description VARCHAR(500) NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'PENDING',
    detected_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE risk_event_medias (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_id BIGINT NOT NULL REFERENCES risk_events (id),
    media_type VARCHAR(20) NOT NULL,
    file_name VARCHAR(255),
    storage_url VARCHAR(2048),
    uploaded_at TIMESTAMP DEFAULT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
